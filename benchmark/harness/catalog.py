"""The sealed fault catalog: opaque fault ids -> recipe parameters + ground truth.

Stored base64-encoded (benchmark/sealed/catalog.b64) so that a grep, an IDE search or
a casual `cat` doesn't show labels. It is sealed against accidental reading, not
encrypted. Nothing the agent can read (bronze, the incidents table) is derived from
the labels: scenario builds use only the recipe, and `leaks.py` checks that no fault id,
template key or root-cause text reaches the lake.

`gen_catalog.generate()` draws the faults from `templates.py` with a fixed seed, so
the file can be regenerated byte for byte (`python -m benchmark.harness gen-catalog
--check`).
"""

from __future__ import annotations

import base64
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from benchmark.harness.templates import TEMPLATES, Recipe

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PATH = ROOT / "benchmark" / "sealed" / "catalog.b64"
SPLITS = ("benchmark", "dev")


@dataclass(frozen=True)
class Label:
    category: str  # a diagnosis category, or "none" (clean run, no fault)
    acceptable: tuple[str, ...]
    root_cause: str


@dataclass(frozen=True)
class Fault:
    fault_id: str
    split: str
    ds: str
    template: str
    params: dict[str, Any]
    label: Label

    @property
    def recipe(self) -> Recipe:
        return TEMPLATES[self.template].recipe(self.params)

    @property
    def is_clean(self) -> bool:
        return self.label.category == "none"


def encode(entries: list[dict[str, Any]]) -> bytes:
    raw = json.dumps(entries, sort_keys=True, separators=(",", ":")).encode()
    b64 = base64.b64encode(raw)
    return b"\n".join(b64[i : i + 76] for i in range(0, len(b64), 76)) + b"\n"


def decode(data: bytes) -> list[dict[str, Any]]:
    return json.loads(base64.b64decode(b"".join(data.split())))


def load(path: Path | None = None, split: str | None = None) -> list[Fault]:
    entries = decode((path or DEFAULT_PATH).read_bytes())
    faults = [
        Fault(
            fault_id=e["fault_id"],
            split=e["split"],
            ds=e["ds"],
            template=e["template"],
            params=e["params"],
            label=Label(e["category"], tuple(e["acceptable"]), e["root_cause"]),
        )
        for e in entries
    ]
    return [f for f in faults if split in (None, "all", f.split)]


def sha256(path: Path | None = None) -> str:
    return hashlib.sha256((path or DEFAULT_PATH).read_bytes()).hexdigest()
